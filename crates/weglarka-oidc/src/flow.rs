//! The authorization code flow's client side: a fresh `state`, `nonce` and PKCE verifier with the
//! authorization URL built from them, and the code exchange (RFC 6749 4.1, RFC 7636). Shared by
//! the admin panel and the CLI's browser login (docs/decisions/0060).

use base64::Engine;
use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use ring::rand::{SecureRandom, SystemRandom};
use url::Url;

use crate::token::{AuthorizationRequest, ClientAuth, TokenSet, authorization_url, token_request};
use crate::{Error, Secret, Transport};

/// `bytes` random bytes from the OS, base64url without padding. The system generator failing means
/// the host cannot give out randomness at all; nothing safe can continue, so this panics.
pub fn random_b64url(bytes: usize) -> String {
    let mut buf = vec![0u8; bytes];
    SystemRandom::new()
        .fill(&mut buf)
        .expect("the operating system cannot provide random bytes");
    URL_SAFE_NO_PAD.encode(buf)
}

/// Bytes of entropy in `state` and `nonce` (256 bits).
const TOKEN_BYTES: usize = 32;
/// Bytes of entropy in the PKCE verifier (43 base64url characters, the RFC 7636 minimum).
const VERIFIER_BYTES: usize = 32;

/// A started authorization code flow: send the user agent to `url`, keep the rest until the
/// callback (`state` and `nonce` are checked there, `verifier` goes into [`exchange_code`]).
pub struct CodeFlow {
    pub url: Url,
    pub state: String,
    pub nonce: String,
    pub verifier: Secret,
}

impl std::fmt::Debug for CodeFlow {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        // The URL's query carries `state` and `nonce` too: only its origin and path are shown.
        f.debug_struct("CodeFlow")
            .field(
                "endpoint",
                &format_args!(
                    "{}{}",
                    self.url.origin().ascii_serialization(),
                    self.url.path()
                ),
            )
            .field("state", &"<redacted>")
            .field("nonce", &"<redacted>")
            .field("verifier", &self.verifier)
            .finish()
    }
}

/// What differs between clients; the random parts are generated by [`begin_code_flow`].
pub struct CodeFlowRequest<'a> {
    pub client_id: &'a str,
    pub redirect_uri: &'a str,
    pub scope: &'a str,
    pub audience: &'a str,
}

/// A fresh `state`, `nonce` and PKCE verifier and the authorization URL carrying them.
pub fn begin_code_flow(authorization_endpoint: &Url, request: &CodeFlowRequest<'_>) -> CodeFlow {
    let state = random_b64url(TOKEN_BYTES);
    let nonce = random_b64url(TOKEN_BYTES);
    let verifier = random_b64url(VERIFIER_BYTES);
    let url = authorization_url(
        authorization_endpoint,
        &AuthorizationRequest {
            client_id: request.client_id,
            redirect_uri: request.redirect_uri,
            scope: request.scope,
            audience: request.audience,
            state: &state,
            nonce: &nonce,
            verifier: &verifier,
        },
    );
    CodeFlow {
        url,
        state,
        nonce,
        verifier: Secret::new(verifier),
    }
}

/// Trades an authorization `code` for tokens. `redirect_uri` must be the one the flow began with.
pub async fn exchange_code<T: Transport>(
    transport: &T,
    token_endpoint: &Url,
    auth: ClientAuth<'_>,
    code: &str,
    redirect_uri: &str,
    verifier: &Secret,
) -> Result<TokenSet, Error> {
    token_request(
        transport,
        token_endpoint,
        auth,
        &[
            ("grant_type", "authorization_code"),
            ("code", code),
            ("redirect_uri", redirect_uri),
            ("code_verifier", verifier.expose()),
        ],
    )
    .await
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::pkce_challenge;
    use crate::testing::Script;

    fn flow() -> CodeFlow {
        begin_code_flow(
            &Url::parse("https://auth.example.com/authorize").unwrap(),
            &CodeFlowRequest {
                client_id: "cli",
                redirect_uri: "http://127.0.0.1:1234/cb",
                scope: "openid",
                audience: "weglarka",
            },
        )
    }

    fn query(url: &Url, key: &str) -> Option<String> {
        url.query_pairs()
            .find(|(k, _)| k == key)
            .map(|(_, v)| v.into_owned())
    }

    #[test]
    fn the_authorization_url_carries_an_s256_challenge_of_the_verifier() {
        let flow = flow();
        assert_eq!(query(&flow.url, "code_challenge_method").unwrap(), "S256");
        assert_eq!(
            query(&flow.url, "code_challenge").unwrap(),
            pkce_challenge(flow.verifier.expose())
        );
        assert_eq!(query(&flow.url, "state").unwrap(), flow.state);
        assert_eq!(query(&flow.url, "nonce").unwrap(), flow.nonce);
        let debug = format!("{flow:?}");
        for secret in [flow.verifier.expose(), &flow.state, &flow.nonce] {
            assert!(!debug.contains(secret), "Debug shows {secret}");
        }
        assert!(debug.contains("https://auth.example.com/authorize"));
    }

    #[test]
    fn every_flow_gets_fresh_randomness() {
        let (a, b) = (flow(), flow());
        assert_ne!(a.state, b.state);
        assert_ne!(a.nonce, b.nonce);
        assert_ne!(a.verifier.expose(), b.verifier.expose());
        // 32 bytes, base64url without padding.
        assert_eq!(a.state.len(), 43);
        assert_eq!(a.verifier.expose().len(), 43);
    }

    #[tokio::test]
    async fn the_exchange_posts_the_code_and_the_verifier_without_a_secret_for_a_public_client() {
        let script = Script::default();
        script.push(
            200,
            r#"{"access_token":"a","token_type":"Bearer","expires_in":900}"#,
        );
        let verifier = Secret::new("verifier-value");
        let set = exchange_code(
            &script,
            &Url::parse("https://auth.example.com/token").unwrap(),
            ClientAuth::Public { id: "cli" },
            "the-code",
            "http://127.0.0.1:1234/cb",
            &verifier,
        )
        .await
        .unwrap();
        assert_eq!(set.access.expose(), "a");
        let seen = script.seen.lock().unwrap();
        assert_eq!(seen[0].1, None);
        let form: Vec<(String, String)> = url::form_urlencoded::parse(seen[0].2.as_bytes())
            .into_owned()
            .collect();
        for (k, v) in [
            ("grant_type", "authorization_code"),
            ("code", "the-code"),
            ("redirect_uri", "http://127.0.0.1:1234/cb"),
            ("code_verifier", "verifier-value"),
            ("client_id", "cli"),
        ] {
            assert!(form.contains(&(k.into(), v.into())), "missing {k}");
        }
        assert!(!seen[0].2.contains("client_secret"));
    }
}
