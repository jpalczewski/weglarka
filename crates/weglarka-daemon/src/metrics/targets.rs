//! Generated Prometheus `file_sd` targets for the scraper named by `[metrics] scraper` (issue #366,
//! `docs/decisions/0064-consumer-watched-generated-config.md`).
//!
//! The scraper reads `/weglarka/generated/current/targets.yml` through its `file_sd_configs` and
//! re-reads it by itself, so the pipeline never reloads or restarts it ([`ApplyMode::ConsumerWatches`]).
//! Every app with `metrics_port` becomes one target `<app>:<metrics_port>`, reachable over its
//! `metrics-<app>` network (#364), with the labels `app` and `__metrics_path__`; the daemon's own
//! listener is one more target on the `[metrics] network`. Label values are validated instance names
//! and validated paths only (ADR 0061, decision 8): the render never contains free text or a secret.

use std::fmt::Write as _;

use weglarka_model::app::{AppSpec, InstanceName};
use weglarka_model::generated::{
    ApplyMode, ConfigGenerator, FileName, GeneratedFile, RenderError, RenderInput,
};

use crate::service::SERVICE_NAME;

/// Stable id in events, `doctor` and `generated.toml`.
pub const ID: &str = "metrics-targets";
/// The file the scraper's `file_sd_configs` lists.
pub const TARGETS_FILE: &str = "targets.yml";
/// A minimal Prometheus config next to [`TARGETS_FILE`] that exists only so `promtool` can check the
/// targets: `promtool` has no standalone `file_sd` check, and `check config` reads a `file_sd` file
/// only through a config that references it. The reference is relative, so it resolves to the
/// version being validated; Prometheus itself never reads this file.
pub const CHECK_FILE: &str = "promtool-check.yml";

const HEADER: &str = "# Generated by weglarka from apps.toml and [metrics]; do not edit.\n";

/// Renders the `file_sd` targets for `scraper`.
pub struct PrometheusTargets {
    scraper: InstanceName,
    /// Port of the daemon's own listener (`[metrics] listen`), reached as `weglarka:<port>`.
    daemon_port: u16,
}

impl PrometheusTargets {
    pub fn new(scraper: InstanceName, daemon_port: u16) -> Self {
        Self {
            scraper,
            daemon_port,
        }
    }
}

impl ConfigGenerator for PrometheusTargets {
    fn id(&self) -> &'static str {
        ID
    }

    fn consumer(&self) -> &InstanceName {
        &self.scraper
    }

    fn render(&self, input: &RenderInput<'_>) -> Result<Vec<GeneratedFile>, RenderError> {
        let mut targets = String::from(HEADER);
        // `AppsFile::apps` is a `BTreeMap`: the targets come out sorted by instance name.
        for (instance, spec) in &input.apps.apps {
            let Some(port) = spec.metrics_port else {
                continue;
            };
            let path = spec
                .metrics_path
                .as_deref()
                .unwrap_or(AppSpec::DEFAULT_METRICS_PATH);
            group(
                &mut targets,
                &format!("{instance}:{port}"),
                &[("app", instance.as_str()), ("__metrics_path__", path)],
            );
        }
        // No `app` label: the daemon's own series carry `app` already, and a target label of the same
        // name would rename theirs to `exported_app`.
        group(
            &mut targets,
            &format!("{SERVICE_NAME}:{}", self.daemon_port),
            &[("__metrics_path__", super::PATH)],
        );
        let check = format!(
            "# Only for `promtool check config`; Prometheus does not read this file.\n\
             scrape_configs:\n  - job_name: \"weglarka-check\"\n    file_sd_configs:\n      \
             - files:\n          - \"{TARGETS_FILE}\"\n"
        );
        Ok(vec![file(TARGETS_FILE, targets)?, file(CHECK_FILE, check)?])
    }

    /// `promtool check config <dir>/promtool-check.yml`: parses the targets strictly and builds every
    /// target from them, the same code path Prometheus uses for `file_sd`.
    fn validate_argv(&self, _: &AppSpec, dir: &str) -> Option<Vec<String>> {
        Some(vec![
            "promtool".into(),
            "check".into(),
            "config".into(),
            format!("{dir}/{CHECK_FILE}"),
        ])
    }

    /// Prometheus re-reads `file_sd` files every `refresh_interval`, and a SIGHUP keeps an unchanged
    /// `file_sd` provider as it is: neither a signal nor a restart is wanted (ADR 0064).
    fn apply_mode(&self) -> ApplyMode {
        ApplyMode::ConsumerWatches
    }
}

/// One target group. Values are instance names, ports and validated paths; they are quoted anyway,
/// with `\` and `"` escaped, so the YAML stays well-formed whatever validation lets through later.
fn group(out: &mut String, target: &str, labels: &[(&str, &str)]) {
    let _ = writeln!(out, "- targets:\n    - {}\n  labels:", quoted(target));
    for (name, value) in labels {
        let _ = writeln!(out, "    {name}: {}", quoted(value));
    }
}

fn quoted(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

fn file(name: &str, text: String) -> Result<GeneratedFile, RenderError> {
    let name = FileName::new(name).map_err(|e| RenderError::Failed {
        id: ID,
        reason: e.to_string(),
    })?;
    Ok(GeneratedFile::new(name, text.into_bytes()))
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use super::*;
    use weglarka_model::app::AppsFile;
    use weglarka_model::generated::Fingerprint;

    const APPS: &str = r#"
[apps.prom]
image = "docker.io/prom/prometheus:v3.5.0"
port = 9090
metrics_port = 9090

[apps.forge]
image = "ghcr.io/example/forge:1"
port = 3000
metrics_port = 9100
metrics_path = "/internal/metrics"

[apps.blog]
image = "ghcr.io/example/blog:1"
port = 8080

[apps.api]
image = "ghcr.io/example/api:1"
port = 8000
metrics_port = 8000
"#;

    fn apps(toml: &str) -> AppsFile {
        toml::from_str(toml).unwrap()
    }

    fn generator() -> PrometheusTargets {
        PrometheusTargets::new(InstanceName::new("prom").unwrap(), 9464)
    }

    fn render(apps: &AppsFile) -> Vec<GeneratedFile> {
        generator()
            .render(&RenderInput {
                apps,
                digests: &BTreeMap::new(),
            })
            .unwrap()
    }

    fn targets(apps: &AppsFile) -> String {
        let files = render(apps);
        let file = files
            .iter()
            .find(|f| f.name().as_str() == TARGETS_FILE)
            .unwrap();
        String::from_utf8(file.bytes().to_vec()).unwrap()
    }

    fn fingerprint(apps: &AppsFile) -> Fingerprint {
        Fingerprint::of(ID, &render(apps)).unwrap()
    }

    fn edit(toml: &str, change: impl FnOnce(&mut AppsFile)) -> AppsFile {
        let mut apps = apps(toml);
        change(&mut apps);
        apps
    }

    fn forge(apps: &mut AppsFile) -> &mut AppSpec {
        apps.apps
            .get_mut(&InstanceName::new("forge").unwrap())
            .unwrap()
    }

    #[test]
    fn the_targets_file_lists_opted_in_apps_and_the_daemon() {
        insta::assert_snapshot!(targets(&apps(APPS)));
    }

    #[test]
    fn the_check_config_references_the_targets_file_relatively() {
        let files = render(&apps(APPS));
        let check = files
            .iter()
            .find(|f| f.name().as_str() == CHECK_FILE)
            .unwrap();
        insta::assert_snapshot!(String::from_utf8(check.bytes().to_vec()).unwrap());
        assert_eq!(
            generator()
                .validate_argv(
                    &toml::from_str("image = \"x:1\"").unwrap(),
                    "/weglarka/generated/v-abc"
                )
                .unwrap(),
            [
                "promtool",
                "check",
                "config",
                "/weglarka/generated/v-abc/promtool-check.yml"
            ]
        );
    }

    #[test]
    fn the_render_is_deterministic_and_independent_of_declaration_order() {
        let a = render(&apps(APPS));
        assert_eq!(a, render(&apps(APPS)), "same input, same bytes");
        // The same apps declared in another order.
        let mut blocks: Vec<&str> = APPS.split("\n\n").collect();
        blocks.reverse();
        let reordered = apps(&blocks.join("\n\n"));
        assert_eq!(a, render(&reordered));
        // Sorted by instance name, the daemon last.
        let text = targets(&apps(APPS));
        let order: Vec<usize> = [
            "\"api:8000\"",
            "\"forge:9100\"",
            "\"prom:9090\"",
            "\"weglarka:9464\"",
        ]
        .iter()
        .map(|t| text.find(t).unwrap())
        .collect();
        assert!(order.windows(2).all(|w| w[0] < w[1]), "{text}");
    }

    #[test]
    fn every_trigger_changes_the_render() {
        let base = fingerprint(&apps(APPS));
        let cases: [(&str, AppsFile); 5] = [
            (
                "opt in",
                edit(APPS, |a| {
                    a.apps
                        .get_mut(&InstanceName::new("blog").unwrap())
                        .unwrap()
                        .metrics_port = Some(9200);
                }),
            ),
            (
                "opt out",
                edit(APPS, |a| {
                    let spec = forge(a);
                    spec.metrics_port = None;
                    spec.metrics_path = None;
                }),
            ),
            (
                "remove",
                edit(APPS, |a| {
                    a.apps.remove(&InstanceName::new("forge").unwrap());
                }),
            ),
            ("port", edit(APPS, |a| forge(a).metrics_port = Some(9101))),
            (
                "path only",
                edit(APPS, |a| forge(a).metrics_path = Some("/m".into())),
            ),
        ];
        for (what, changed) in cases {
            assert_ne!(fingerprint(&changed), base, "{what}");
        }
        // Back to the default path: the label says `/metrics`.
        let defaulted = targets(&edit(APPS, |a| forge(a).metrics_path = None));
        assert!(
            defaulted.contains("- \"forge:9100\"\n  labels:\n    app: \"forge\"\n    __metrics_path__: \"/metrics\"\n"),
            "{defaulted}"
        );
        // A change that does not touch metrics leaves the render alone.
        let unrelated = edit(APPS, |a| forge(a).port = Some(3001));
        assert_eq!(fingerprint(&unrelated), base);
    }

    #[test]
    fn without_opted_in_apps_only_the_daemon_is_listed() {
        let text = targets(&apps("[apps.blog]\nimage = \"ghcr.io/example/blog:1\"\n"));
        assert_eq!(text.matches("- targets:").count(), 1, "{text}");
        assert!(text.contains("\"weglarka:9464\""), "{text}");
        assert!(!text.contains("app:"), "{text}");
    }

    #[test]
    fn the_consumer_is_not_reloaded() {
        assert_eq!(generator().apply_mode(), ApplyMode::ConsumerWatches);
    }

    #[test]
    fn quoting_escapes_what_yaml_needs() {
        assert_eq!(quoted(r#"a"b\c"#), r#""a\"b\\c""#);
    }
}
