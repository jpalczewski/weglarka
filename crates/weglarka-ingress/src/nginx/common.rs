/// The three expressions the shared proxy headers are built from. `behind` reuses the trust maps
/// (ADR 0007/0032); `edge` has no trusted peer, so the values are nginx's own.
pub(super) struct Forwarded {
    pub(super) real_ip: &'static str,
    pub(super) xff: &'static str,
    pub(super) proto: &'static str,
    pub(super) fwd_host: &'static str,
    /// The scheme of the client's request as the provider must see it (`X-Original-URL`): the
    /// trusted-proxy scheme in `behind`, always `https` in `edge`. Never `$scheme`: behind Traefik
    /// nginx listens on plain HTTP, and Authelia answers 400 to a non-`https` target.
    pub(super) original_proto: &'static str,
}

/// Where a protected location's `Remote-*` values come from: the variables its `auth_request_set`
/// lines fill from the authz response. Everywhere else the same headers are stripped.
pub(super) struct AuthVars;

impl AuthVars {
    /// `(request header, variable)`; the provider's own response headers are the lower-case
    /// `$upstream_http_remote_*` counterparts (see [`write_auth_request`]).
    const HEADERS: [(&'static str, &'static str); 4] = [
        ("Remote-User", "$wg_user"),
        ("Remote-Groups", "$wg_groups"),
        ("Remote-Name", "$wg_name"),
        ("Remote-Email", "$wg_email"),
    ];
}

pub(super) use crate::plan::AUTHZ_PATH as AUTHZ_LOCATION;

/// JSON access log format. `path` is `$uri` (no query string, so tokens in URLs do not
/// end up in logs); `upstream_response_time` is a string (`-` or a list on retry).
pub(super) const LOG_FORMAT: &str = concat!(
    "{\"time\":\"$time_iso8601\",\"app\":\"$app\",\"host\":\"$host\",",
    "\"remote_addr\":\"$remote_addr\",\"method\":\"$request_method\",\"path\":\"$uri\",",
    "\"status\":$status,\"bytes_sent\":$body_bytes_sent,\"request_time\":$request_time,",
    "\"upstream_response_time\":\"$upstream_response_time\",\"request_id\":\"$request_id\",",
    "\"user_agent\":\"$http_user_agent\"}"
);

/// The fixed part of every mode: the process preamble and the `events` block.
pub(super) fn write_preamble(c: &mut Conf, tls_fingerprint: Option<&str>) {
    c.line("# Generated by weglarka — do not edit.");
    if let Some(fingerprint) = tls_fingerprint {
        c.line(&format!("# tls material: fingerprint {fingerprint}"));
    }
    c.line("worker_processes 1;");
    c.line("pid /tmp/nginx.pid;");
    c.line("error_log /dev/stderr warn;");
    c.blank();
    c.block("events", |c| c.line("worker_connections 1024;"));
    c.blank();
}

/// Directives at the top of `http {}` that do not depend on the mode: the read-only-root writable
/// paths (ADR 0014), the resolver used by the variable `proxy_pass`, and the access-log format.
pub(super) fn write_http_scaffolding(c: &mut Conf, o: &NginxOptions) {
    c.line("server_tokens off;");
    c.line("client_body_temp_path /tmp/client_body;");
    c.line("proxy_temp_path /tmp/proxy;");
    c.line("fastcgi_temp_path /tmp/fastcgi;");
    c.line("uwsgi_temp_path /tmp/uwsgi;");
    c.line("scgi_temp_path /tmp/scgi;");
    c.blank();
    let resolvers: Vec<String> = o
        .resolvers
        .iter()
        .map(|ip| match ip {
            IpAddr::V4(v4) => v4.to_string(),
            IpAddr::V6(v6) => format!("[{v6}]"),
        })
        .collect();
    // `valid=1s`: a blue-green switch (ADR 0046) moves the instance alias to a new container, and
    // nginx must not keep the old address longer than the drain that follows. aardvark is local, so
    // the extra lookups cost nothing.
    c.line(&format!(
        "resolver {} valid=1s ipv6=off;",
        resolvers.join(" ")
    ));
    c.line("resolver_timeout 2s;");
    c.blank();
}

pub(super) fn write_upgrade_map(c: &mut Conf) {
    c.block("map $http_upgrade $connection_upgrade", |c| {
        c.line("default upgrade;");
        c.line("'' close;");
    });
}

/// `access_log_skip_paths` (issue #181): two maps decide per request whether it is logged. The first
/// matches `"$app $uri"` against the routed apps' entries (regexes only — no map hash to size, and
/// an exact entry is just anchored), the second lets only `status < 400` through, so a failing poll
/// is still logged. `$app` is the server-level or location-level variable the log format already
/// uses. Returns whether `$weglarka_loggable` exists; nothing is emitted when no app lists a path.
fn write_log_skip_maps(c: &mut Conf, plan: &Plan<'_>) -> bool {
    let mut rules = Vec::new();
    for app in plan.apps.iter().filter(|app| app.active) {
        for path in &app.ingress.access_log_skip_paths {
            // `.` is the only regex metacharacter the path alphabet allows (see `check_skip_path`).
            let escaped = path.replace('.', "\\.");
            let tail = if path.ends_with('/') { "" } else { "$" };
            let instance = app.instance.as_str().replace('.', "\\.");
            rules.push(format!("\"~^{instance} {escaped}{tail}\" 1;"));
        }
    }
    if rules.is_empty() {
        return false;
    }
    c.line("# Paths an app asked to keep out of the access log (while they succeed).");
    c.block("map \"$app $uri\" $weglarka_skip_path", |c| {
        c.line("default 0;");
        for rule in &rules {
            c.line(rule);
        }
    });
    c.block(
        "map \"$weglarka_skip_path:$status\" $weglarka_loggable",
        |c| {
            c.line("default 1;");
            c.line("\"~^1:[123][0-9][0-9]$\" 0;");
        },
    );
    true
}

/// `$app` for requests that never reach a `set $app` (catch-all servers, and requests nginx rejects
/// with 400 before the rewrite phase). A `map` variable is changeable, so the `set $app` in the
/// `server`/`location` blocks still wins where it runs.
fn write_app_default(c: &mut Conf) {
    c.block("map \"\" $app", |c| {
        c.line(&format!("default \"{NO_APP}\";"));
    });
}

/// Where the access log takes the client address from.
#[derive(Clone, Copy)]
pub(super) enum ClientAddr {
    /// `$remote_addr` is the client (`behind`, `edge` without a CDN or the forwarder).
    Direct,
    /// `edge` behind the forwarder: `$weglarka_peer` is the client (see [`write_peer_address`]).
    Proxied,
    /// `edge` behind a CDN: `$weglarka_client` is the visitor, the peer is the CDN's address.
    BehindCdn { proxied: bool },
}

impl ClientAddr {
    /// The variable holding the TCP peer's address.
    pub(super) fn peer(self) -> &'static str {
        match self {
            Self::Direct | Self::BehindCdn { proxied: false } => "$remote_addr",
            Self::Proxied | Self::BehindCdn { proxied: true } => "$weglarka_peer",
        }
    }
}

/// The connection's peer address in `edge` behind the forwarder. `$remote_addr` is replaced from the
/// PROXY header only when the request is processed (`realip` runs after the headers are parsed), so a
/// request nginx rejects earlier still has `unix:`; the PROXY header itself is available from the start.
/// A connection on the probe socket has no PROXY header: its peer stays the literal `unix:` instead of
/// the empty `$proxy_protocol_addr`.
pub(super) fn write_peer_address(c: &mut Conf) {
    c.block(
        "map \"$remote_addr|$proxy_protocol_addr\" $weglarka_peer",
        |c| {
            c.line("\"unix:|\" \"unix:\";");
            c.line("\"~^unix:\\|(?<announced>.+)$\" $announced;");
            c.line("default $remote_addr;");
        },
    );
}

pub(super) fn write_log(c: &mut Conf, client: ClientAddr, plan: &Plan<'_>) {
    c.line("# App name for the access log; `-` unless a `server`/`location` sets it.");
    write_app_default(c);
    c.line("log_format weglarka escape=json");
    // Behind a CDN `remote_addr` is the visitor and the CDN's edge address is kept as `peer`.
    let format = match client {
        ClientAddr::BehindCdn { .. } => LOG_FORMAT.replace(
            "\"remote_addr\":\"$remote_addr\"",
            &format!(
                "\"remote_addr\":\"$weglarka_client\",\"peer\":\"{}\"",
                client.peer()
            ),
        ),
        ClientAddr::Direct | ClientAddr::Proxied => {
            LOG_FORMAT.replace("$remote_addr", client.peer())
        }
    };
    c.line(&format!("    '{format}';"));
    if write_log_skip_maps(c, plan) {
        c.line("access_log /dev/stdout weglarka if=$weglarka_loggable;");
    } else {
        c.line("access_log /dev/stdout weglarka;");
    }
}

/// `$weglarka_proto`, with one exception to "the scheme of the listener": a request on the probe
/// socket (`$remote_addr` is the literal `unix:` there and nowhere else, ADR 0054) may announce
/// `X-Forwarded-Proto: https`. The socket is `0700` and mounted into nginx only, so the sender is the
/// daemon. It does so when it fetches from the identity provider, whose OIDC endpoints refuse a
/// request that claims to be plain HTTP (issue #321). Anyone else gets `fallback`.
pub(super) fn write_probe_proto_map(c: &mut Conf, fallback: &str) {
    c.block(
        "map \"$remote_addr:$http_x_forwarded_proto\" $weglarka_proto",
        |c| {
            c.line(&format!("default {fallback};"));
            c.line("\"unix::https\" https;");
        },
    );
}

/// The full proxy header set. At `http {}` level (`auth: None`) the `Remote-*` identity headers are
/// set to the empty string, which removes whatever a client sent (same discipline as `X-Forwarded-*`,
/// ADR 0007) in every location, static sites and the webhook included. nginx's `proxy_set_header`
/// replaces *all* inherited headers at the first use on a level, so a protected location calls this
/// again with `Some(AuthVars)` and gets the whole set back, `Remote-*` taken from the authz result.
pub(super) fn write_proxy_headers(c: &mut Conf, forwarded: &Forwarded, auth: Option<AuthVars>) {
    c.line("proxy_http_version 1.1;");
    c.line("proxy_set_header Host $host;");
    c.line(&format!(
        "proxy_set_header X-Real-IP {};",
        forwarded.real_ip
    ));
    c.line(&format!(
        "proxy_set_header X-Forwarded-For {};",
        forwarded.xff
    ));
    c.line(&format!(
        "proxy_set_header X-Forwarded-Proto {};",
        forwarded.proto
    ));
    c.line(&format!(
        "proxy_set_header X-Forwarded-Host {};",
        forwarded.fwd_host
    ));
    c.line("proxy_set_header X-Request-Id $request_id;");
    c.line("proxy_set_header Upgrade $http_upgrade;");
    c.line("proxy_set_header Connection $connection_upgrade;");
    for (header, variable) in AuthVars::HEADERS {
        let value = if auth.is_some() { variable } else { "\"\"" };
        c.line(&format!("proxy_set_header {header} {value};"));
    }
    c.line("add_header X-Request-Id $request_id always;");
}

/// `http {}` pieces of forward auth, present only when an active app uses it: the probe-socket test
/// and the redirect target of a 401 that carries no `Location` (a bad `Authorization` header, say —
/// a 302 with an empty `Location` would be broken).
pub(super) fn write_auth_maps(c: &mut Conf, plan: &Plan<'_>) {
    let Some(identity) = plan.forward_auth() else {
        return;
    };
    c.line("# Forward auth (docs/decisions/0052).");
    // The probe socket is the only listener without PROXY header or real_ip, so `$remote_addr` stays
    // `unix:` there and nowhere else: the daemon is exempt structurally, with no address list.
    c.block("map $remote_addr $weglarka_probe", |c| {
        c.line("\"unix:\" 1;");
        c.line("default 0;");
    });
    c.block("map $wg_redirect $wg_redirect_or_portal", |c| {
        c.line(&format!("\"\" \"{}/\";", identity.issuer));
        c.line("default $wg_redirect;");
    });
    c.blank();
}

/// The `auth_request` of a protected location and what it reads from the answer. A 401 goes to the
/// provider's login (its `Location`, else the portal); 403 and a failed subrequest (500) stay errors.
pub(super) fn write_auth_request(c: &mut Conf) {
    c.line(&format!("auth_request {AUTHZ_LOCATION};"));
    for (variable, header) in [
        ("$wg_user", "remote_user"),
        ("$wg_groups", "remote_groups"),
        ("$wg_name", "remote_name"),
        ("$wg_email", "remote_email"),
        ("$wg_redirect", "location"),
    ] {
        c.line(&format!(
            "auth_request_set {variable} $upstream_http_{header};"
        ));
    }
    c.line("error_page 401 =302 $wg_redirect_or_portal;");
}

/// The internal location a `server` with protected apps carries once. The provider is a *variable*
/// upstream resolved at request time, so a provider that is not running never fails `nginx -t` and
/// never blocks reloads of other apps (its absence fails closed with a 500 instead).
pub(super) fn write_authz_location(c: &mut Conf, identity: &IdentityRoute, forwarded: &Forwarded) {
    c.block(&format!("location = {AUTHZ_LOCATION}"), |c| {
        c.line("internal;");
        c.block("if ($weglarka_probe)", |c| c.line("return 200;"));
        c.line(&format!("set $wg_idp \"http://{}\";", identity.upstream));
        c.line("proxy_pass $wg_idp/api/authz/auth-request;");
        c.line("proxy_pass_request_body off;");
        c.line("proxy_set_header Content-Length \"\";");
        c.line("proxy_set_header Connection \"\";");
        // The provider must not see identity headers a client made up either.
        for (header, _) in AuthVars::HEADERS {
            c.line(&format!("proxy_set_header {header} \"\";"));
        }
        c.line("proxy_set_header X-Original-Method $request_method;");
        c.line(&format!(
            "proxy_set_header X-Original-URL {}://$host$request_uri;",
            forwarded.original_proto
        ));
        c.line(&format!(
            "proxy_set_header X-Forwarded-For {};",
            forwarded.xff
        ));
    });
}

/// The `$app` value of a server that hosts no single app (several apps, or none).
pub(super) const NO_APP: &str = "-";

/// `set $app "<name>";`: the app name the access log attributes the server's requests to. Every
/// `server` and, in shared servers, every app `location` goes through here.
pub(super) fn set_app(c: &mut Conf, name: &str) {
    c.line(&format!("set $app \"{name}\";"));
}

/// The `listen` parameter that makes a server the fallback for unknown `Host`/SNI values.
fn default_server_suffix(default_server: bool) -> &'static str {
    if default_server {
        " default_server"
    } else {
        ""
    }
}

pub(super) fn listen(c: &mut Conf, port: u16, default_server: bool) {
    let suffix = default_server_suffix(default_server);
    c.line(&format!("listen {port}{suffix};"));
}

/// The daemon's probe socket (docs/decisions/0054): plain HTTP, no `ssl`, no `proxy_protocol`, so
/// `$remote_addr` stays `unix:` and no PROXY header is ever expected on it. The directory is `0700`
/// and mounted into nginx only; that, not a config rule, keeps every other peer off it.
pub(super) fn listen_probe(c: &mut Conf, o: &NginxOptions, default_server: bool) {
    let suffix = default_server_suffix(default_server);
    c.line(&format!("listen unix:{}{suffix};", o.probe_socket));
}

/// `listen` of an `edge` plain-HTTP server: the TCP port (only redirects and ACME; nothing is published
/// on it, the daemon's probe has its own socket) plus the forwarder's unix socket with `proxy_protocol`.
pub(super) fn listen_edge_plain(c: &mut Conf, o: &NginxOptions, default_server: bool) {
    listen(c, o.listen_port, default_server);
    if let Some(dir) = &o.proxy_socket_dir {
        let suffix = default_server_suffix(default_server);
        c.line(&format!(
            "listen unix:{dir}/{PLAIN_SOCKET}{suffix} proxy_protocol;"
        ));
    }
}

/// `listen` of an `edge` TLS server (`default_server` for the certificate-less one); see
/// [`listen_edge_plain`].
pub(super) fn listen_edge_tls(c: &mut Conf, o: &NginxOptions, default_server: bool) {
    let suffix = default_server_suffix(default_server);
    c.line(&format!("listen {} ssl{suffix};", o.https_listen_port));
    if let Some(dir) = &o.proxy_socket_dir {
        c.line(&format!(
            "listen unix:{dir}/{TLS_SOCKET} ssl{suffix} proxy_protocol;"
        ));
    }
}

/// The default server: a foreign `Host` gets nothing.
pub(super) fn write_default_server(c: &mut Conf, o: &NginxOptions) {
    c.block("server", |c| {
        listen_edge_plain(c, o, true);
        listen_probe(c, o, true);
        c.line("server_name _;");
        set_app(c, NO_APP);
        c.line("return 444;");
    });
}

/// Webhook locations: only the listed prefixes, POST, small body limit.
pub(super) fn write_webhook_body(c: &mut Conf, plan: &Plan<'_>, o: &NginxOptions) {
    c.line(&format!(
        "client_max_body_size {};",
        o.webhook_max_body_bytes
    ));
    for path in &o.webhook_paths {
        c.block(&format!("location ^~ {path}"), |c| {
            c.block("limit_except POST", |c| c.line("deny all;"));
            c.line(&format!(
                "set $upstream \"http://{WEBHOOK_UPSTREAM_HOST}:{}\";",
                plan.webhook.upstream_port
            ));
            c.line("proxy_pass $upstream;");
        });
    }
    c.block("location /", |c| c.line("return 404;"));
}

/// `geo <address> <variable>` that is `1` for an address inside `peers` and `0` otherwise: the
/// trust decision of `behind` (`$realip_remote_addr`) and of `edge` behind a CDN (`$remote_addr`).
pub(super) fn write_trusted_peers(c: &mut Conf, address: &str, variable: &str, peers: &[Cidr]) {
    c.block(&format!("geo {address} {variable}"), |c| {
        c.line("default 0;");
        for net in peers {
            c.line(&format!("{net} 1;"));
        }
    });
}

pub(super) fn join_domains(domains: &[Domain]) -> String {
    let mut s = String::new();
    for (i, d) in domains.iter().enumerate() {
        if i > 0 {
            s.push(' ');
        }
        let _ = write!(s, "{d}");
    }
    s
}
