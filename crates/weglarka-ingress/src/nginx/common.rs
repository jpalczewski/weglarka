//! Pieces shared by both modes: preamble, `http {}` scaffolding, access log, proxy headers, the
//! `listen` helpers and the non-app servers.

use std::fmt::Write as _;
use std::net::IpAddr;

use super::conf::Conf;
use super::{NginxOptions, PLAIN_SOCKET, TLS_SOCKET};
use crate::plan::{Cidr, Domain, Plan, WEBHOOK_UPSTREAM_HOST};

/// The three expressions the shared proxy headers are built from. `behind` reuses the trust maps
/// (ADR 0007/0032); `edge` has no trusted peer, so the values are nginx's own.
pub(super) struct Forwarded {
    pub(super) real_ip: &'static str,
    pub(super) xff: &'static str,
    pub(super) proto: &'static str,
    pub(super) fwd_host: &'static str,
}

/// JSON access log format. `path` is `$uri` (no query string, so tokens in URLs do not
/// end up in logs); `upstream_response_time` is a string (`-` or a list on retry).
pub(super) const LOG_FORMAT: &str = concat!(
    "{\"time\":\"$time_iso8601\",\"app\":\"$app\",\"host\":\"$host\",",
    "\"remote_addr\":\"$remote_addr\",\"method\":\"$request_method\",\"path\":\"$uri\",",
    "\"status\":$status,\"bytes_sent\":$body_bytes_sent,\"request_time\":$request_time,",
    "\"upstream_response_time\":\"$upstream_response_time\",\"request_id\":\"$request_id\",",
    "\"user_agent\":\"$http_user_agent\"}"
);

/// The fixed part of every mode: the process preamble and the `events` block.
pub(super) fn write_preamble(c: &mut Conf, tls_fingerprint: Option<&str>) {
    c.line("# Generated by weglarka — do not edit.");
    if let Some(fingerprint) = tls_fingerprint {
        c.line(&format!("# tls material: fingerprint {fingerprint}"));
    }
    c.line("worker_processes 1;");
    c.line("pid /tmp/nginx.pid;");
    c.line("error_log /dev/stderr warn;");
    c.blank();
    c.block("events", |c| c.line("worker_connections 1024;"));
    c.blank();
}

/// Directives at the top of `http {}` that do not depend on the mode: the read-only-root writable
/// paths (ADR 0014), the resolver used by the variable `proxy_pass`, and the access-log format.
pub(super) fn write_http_scaffolding(c: &mut Conf, o: &NginxOptions) {
    c.line("server_tokens off;");
    c.line("client_body_temp_path /tmp/client_body;");
    c.line("proxy_temp_path /tmp/proxy;");
    c.line("fastcgi_temp_path /tmp/fastcgi;");
    c.line("uwsgi_temp_path /tmp/uwsgi;");
    c.line("scgi_temp_path /tmp/scgi;");
    c.blank();
    let resolvers: Vec<String> = o
        .resolvers
        .iter()
        .map(|ip| match ip {
            IpAddr::V4(v4) => v4.to_string(),
            IpAddr::V6(v6) => format!("[{v6}]"),
        })
        .collect();
    // `valid=1s`: a blue-green switch (ADR 0046) moves the instance alias to a new container, and
    // nginx must not keep the old address longer than the drain that follows. aardvark is local, so
    // the extra lookups cost nothing.
    c.line(&format!(
        "resolver {} valid=1s ipv6=off;",
        resolvers.join(" ")
    ));
    c.line("resolver_timeout 2s;");
    c.blank();
}

pub(super) fn write_upgrade_map(c: &mut Conf) {
    c.block("map $http_upgrade $connection_upgrade", |c| {
        c.line("default upgrade;");
        c.line("'' close;");
    });
}

/// `access_log_skip_paths` (issue #181): two maps decide per request whether it is logged. The first
/// matches `"$app $uri"` against the routed apps' entries (regexes only — no map hash to size, and
/// an exact entry is just anchored), the second lets only `status < 400` through, so a failing poll
/// is still logged. `$app` is the server-level or location-level variable the log format already
/// uses. Returns whether `$weglarka_loggable` exists; nothing is emitted when no app lists a path.
fn write_log_skip_maps(c: &mut Conf, plan: &Plan<'_>) -> bool {
    let mut rules = Vec::new();
    for app in plan.apps.iter().filter(|app| app.active) {
        for path in &app.ingress.access_log_skip_paths {
            // `.` is the only regex metacharacter the path alphabet allows (see `check_skip_path`).
            let escaped = path.replace('.', "\\.");
            let tail = if path.ends_with('/') { "" } else { "$" };
            let instance = app.instance.as_str().replace('.', "\\.");
            rules.push(format!("\"~^{instance} {escaped}{tail}\" 1;"));
        }
    }
    if rules.is_empty() {
        return false;
    }
    c.line("# Paths an app asked to keep out of the access log (while they succeed).");
    c.block("map \"$app $uri\" $weglarka_skip_path", |c| {
        c.line("default 0;");
        for rule in &rules {
            c.line(rule);
        }
    });
    c.block(
        "map \"$weglarka_skip_path:$status\" $weglarka_loggable",
        |c| {
            c.line("default 1;");
            c.line("\"~^1:[123][0-9][0-9]$\" 0;");
        },
    );
    true
}

/// Where the access log takes the client address from.
#[derive(Clone, Copy)]
pub(super) enum ClientAddr {
    /// `$remote_addr` is the client (`behind`, `edge` without a CDN).
    Direct,
    /// `edge` behind a CDN: `$weglarka_client` is the visitor, `$remote_addr` the CDN's address.
    BehindCdn,
}

pub(super) fn write_log(c: &mut Conf, client: ClientAddr, plan: &Plan<'_>) {
    c.line("# App name for the access log; set in each `server`.");
    c.line("log_format weglarka escape=json");
    // Behind a CDN `remote_addr` is the visitor and the CDN's edge address is kept as `peer`.
    let format = match client {
        ClientAddr::BehindCdn => LOG_FORMAT.replace(
            "\"remote_addr\":\"$remote_addr\"",
            "\"remote_addr\":\"$weglarka_client\",\"peer\":\"$remote_addr\"",
        ),
        ClientAddr::Direct => LOG_FORMAT.to_owned(),
    };
    c.line(&format!("    '{format}';"));
    if write_log_skip_maps(c, plan) {
        c.line("access_log /dev/stdout weglarka if=$weglarka_loggable;");
    } else {
        c.line("access_log /dev/stdout weglarka;");
    }
}

pub(super) fn write_proxy_headers(c: &mut Conf, forwarded: &Forwarded) {
    c.line("proxy_http_version 1.1;");
    c.line("proxy_set_header Host $host;");
    c.line(&format!(
        "proxy_set_header X-Real-IP {};",
        forwarded.real_ip
    ));
    c.line(&format!(
        "proxy_set_header X-Forwarded-For {};",
        forwarded.xff
    ));
    c.line(&format!(
        "proxy_set_header X-Forwarded-Proto {};",
        forwarded.proto
    ));
    c.line(&format!(
        "proxy_set_header X-Forwarded-Host {};",
        forwarded.fwd_host
    ));
    c.line("proxy_set_header X-Request-Id $request_id;");
    c.line("proxy_set_header Upgrade $http_upgrade;");
    c.line("proxy_set_header Connection $connection_upgrade;");
    c.line("add_header X-Request-Id $request_id always;");
}

/// The `$app` value of a server that hosts no single app (several apps, or none).
pub(super) const NO_APP: &str = "-";

/// `set $app "<name>";`: the app name the access log attributes the server's requests to. Every
/// `server` and, in shared servers, every app `location` goes through here.
pub(super) fn set_app(c: &mut Conf, name: &str) {
    c.line(&format!("set $app \"{name}\";"));
}

/// The `listen` parameter that makes a server the fallback for unknown `Host`/SNI values.
fn default_server_suffix(default_server: bool) -> &'static str {
    if default_server {
        " default_server"
    } else {
        ""
    }
}

pub(super) fn listen(c: &mut Conf, port: u16, default_server: bool) {
    let suffix = default_server_suffix(default_server);
    c.line(&format!("listen {port}{suffix};"));
}

/// `listen` of an `edge` plain-HTTP server: the TCP port (the daemon's health probe, nothing is
/// published on it any more) plus the forwarder's unix socket with `proxy_protocol`.
pub(super) fn listen_edge_plain(c: &mut Conf, o: &NginxOptions, default_server: bool) {
    listen(c, o.listen_port, default_server);
    if let Some(dir) = &o.proxy_socket_dir {
        let suffix = default_server_suffix(default_server);
        c.line(&format!(
            "listen unix:{dir}/{PLAIN_SOCKET}{suffix} proxy_protocol;"
        ));
    }
}

/// `listen` of an `edge` TLS server (`default_server` for the certificate-less one); see
/// [`listen_edge_plain`].
pub(super) fn listen_edge_tls(c: &mut Conf, o: &NginxOptions, default_server: bool) {
    let suffix = default_server_suffix(default_server);
    c.line(&format!("listen {} ssl{suffix};", o.https_listen_port));
    if let Some(dir) = &o.proxy_socket_dir {
        c.line(&format!(
            "listen unix:{dir}/{TLS_SOCKET} ssl{suffix} proxy_protocol;"
        ));
    }
}

/// The default server: a foreign `Host` gets nothing.
pub(super) fn write_default_server(c: &mut Conf, o: &NginxOptions) {
    c.block("server", |c| {
        listen_edge_plain(c, o, true);
        c.line("server_name _;");
        set_app(c, NO_APP);
        c.line("return 444;");
    });
}

/// Webhook locations: only the listed prefixes, POST, small body limit.
pub(super) fn write_webhook_body(c: &mut Conf, plan: &Plan<'_>, o: &NginxOptions) {
    c.line(&format!(
        "client_max_body_size {};",
        o.webhook_max_body_bytes
    ));
    for path in &o.webhook_paths {
        c.block(&format!("location ^~ {path}"), |c| {
            c.block("limit_except POST", |c| c.line("deny all;"));
            c.line(&format!(
                "set $upstream \"http://{WEBHOOK_UPSTREAM_HOST}:{}\";",
                plan.webhook.upstream_port
            ));
            c.line("proxy_pass $upstream;");
        });
    }
    c.block("location /", |c| c.line("return 404;"));
}

/// `geo <address> <variable>` that is `1` for an address inside `peers` and `0` otherwise: the
/// trust decision of `behind` (`$realip_remote_addr`) and of `edge` behind a CDN (`$remote_addr`).
pub(super) fn write_trusted_peers(c: &mut Conf, address: &str, variable: &str, peers: &[Cidr]) {
    c.block(&format!("geo {address} {variable}"), |c| {
        c.line("default 0;");
        for net in peers {
            c.line(&format!("{net} 1;"));
        }
    });
}

pub(super) fn join_domains(domains: &[Domain]) -> String {
    let mut s = String::new();
    for (i, d) in domains.iter().enumerate() {
        if i > 0 {
            s.push(' ');
        }
        let _ = write!(s, "{d}");
    }
    s
}
