//! Pieces shared by both modes: preamble, `http {}` scaffolding, access log, proxy headers, the
//! `listen` helpers and the non-app servers.

use std::fmt::Write as _;
use std::net::IpAddr;

use super::conf::Conf;
use super::{NginxOptions, PLAIN_SOCKET, TLS_SOCKET};
