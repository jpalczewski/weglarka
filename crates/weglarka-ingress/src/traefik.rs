//! Dynamiczny plik Traefika (router per apka → `host.docker.internal:<port>`, router webhooków → ten sam service). **Własność: sesja c.**
//!
//! Jedna usługa (nginx Węglarki), wiele routerów; to nginx rozdziela ruch po `Host`. Router jest
//! jeden na apkę (wiele `Host(...)` w regule), nie na domenę — nazwa routera z domeny
//! mogłaby kolidować (`a.b-c` vs `a-b.c`), a nazwa instancji jest unikalna z konstrukcji.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use weglarka_core::app::{AppSpec, InstanceName};
use weglarka_core::config::{HostConfig, IngressMode};

use crate::plan::{Domain, IngressError, Plan};

#[derive(Debug, Clone)]
pub struct TraefikOptions {
    pub entrypoint: String,
    /// `None` — router bez `tls.certResolver` (np. certy wystawia ktoś inny).
    pub cert_resolver: Option<String>,
    /// Host nginx widziany z kontenera Traefika.
    pub upstream_host: String,
}

impl Default for TraefikOptions {
    fn default() -> Self {
        Self {
            entrypoint: "https".to_owned(),
            cert_resolver: Some("letsencrypt".to_owned()),
            upstream_host: "host.docker.internal".to_owned(),
        }
    }
}

const SERVICE: &str = "weglarka";

fn check_ident(name: &'static str, value: &str, extra: &[u8]) -> Result<(), IngressError> {
    let ok = !value.is_empty()
        && value.len() <= 63
        && value
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_' || extra.contains(&b));
    if ok {
        Ok(())
    } else {
        Err(IngressError::InvalidOption {
            name,
            reason: format!("{value:?}: expected 1-63 chars of [A-Za-z0-9_-]"),
        })
    }
}

impl TraefikOptions {
    fn validate(&self) -> Result<(), IngressError> {
        check_ident("entrypoint", &self.entrypoint, b"")?;
        if let Some(r) = &self.cert_resolver {
            check_ident("cert_resolver", r, b"")?;
        }
        // Host DNS: litery, cyfry, `-`, `.`; nie może wyglądać na nic poza nazwą hosta.
        check_ident("upstream_host", &self.upstream_host, b".")
    }
}

/// Generuje YAML pliku dynamicznego. Kolejność: routery apek (wg nazwy instancji), potem webhooki.
pub fn generate(
    host: &HostConfig,
    apps: &BTreeMap<InstanceName, AppSpec>,
    options: &TraefikOptions,
) -> Result<String, IngressError> {
    options.validate()?;
    let plan = Plan::build(host, apps)?;
    if plan.mode != IngressMode::Behind {
        return Err(IngressError::UnsupportedMode(plan.mode));
    }

    let mut y = String::from("# Generated by weglarka — do not edit.\nhttp:\n  routers:\n");
    for app in &plan.apps {
        router(
            &mut y,
            &format!("weglarka-app-{}", app.instance),
            &app.domains,
            options,
        );
    }
    router(
        &mut y,
        "weglarka-webhooks",
        std::slice::from_ref(&plan.webhook.domain),
        options,
    );

    let _ = write!(
        y,
        "  services:\n    {SERVICE}:\n      loadBalancer:\n        passHostHeader: true\n        servers:\n          - url: \"http://{}:{}\"\n",
        options.upstream_host,
        plan.bind.port()
    );
    Ok(y)
}

fn router(y: &mut String, name: &str, domains: &[Domain], o: &TraefikOptions) {
    let rule = domains
        .iter()
        .map(|d| format!("Host(`{d}`)"))
        .collect::<Vec<_>>()
        .join(" || ");
    let _ = write!(
        y,
        "    {name}:\n      rule: \"{rule}\"\n      entryPoints:\n        - {}\n      service: {SERVICE}\n",
        o.entrypoint
    );
    if let Some(resolver) = &o.cert_resolver {
        let _ = write!(y, "      tls:\n        certResolver: {resolver}\n");
    } else {
        y.push_str("      tls: {}\n");
    }
}
